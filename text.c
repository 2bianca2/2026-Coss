static uint8_t get_char_idx(char c)
{
    if (c == ' ') return 0;
    if (c >= '0' && c <= '9') return c - '0' + 1;
    if (c >= 'A' && c <= 'Z') return c - 'A' + 11;
    if (c >= 'a' && c <= 'z') return c - 'a' + 11;
    switch (c) {
        case ':': return 37;
        case '.': return 38;
        case '/': return 39;
        case '-': return 40;
        case '%': return 41;
        default:  return 0;
    }
}

void lcd_draw_char(uint16_t x, uint16_t y, char c, uint8_t r, uint8_t g, uint8_t b)
{
    uint8_t idx = get_char_idx(c);
    for (uint8_t i = 0; i < 5; i++) {
        uint8_t line = pgm_read_byte(&font5x7[idx][i]);
        for (uint8_t j = 0; j < 7; j++) {
            if (line & (1 << j))
                lcd_draw_pixel(x + i, y + j, r, g, b);
        }
    }
}

void lcd_draw_string(uint16_t x, uint16_t y, const char *str, uint8_t r, uint8_t g, uint8_t b)
{
    while (*str) {
        lcd_draw_char(x, y, *str, r, g, b);
        x += 6;
        str++;
    }
}

void lcd_draw_string_P(uint16_t x, uint16_t y, const char *str_p, uint8_t r, uint8_t g, uint8_t b)
{
    char c;
    while ((c = (char)pgm_read_byte(str_p)) != '\0') {
        lcd_draw_char(x, y, c, r, g, b);
        x += 6;
        str_p++;
    }
}
